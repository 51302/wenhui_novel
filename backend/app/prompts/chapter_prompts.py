COMBAT_WRITING_GUIDE = """【战斗描写铁律 —— 有来有回、有血有肉、有张有弛】

=== 战斗四步节奏（必须严格遵守）===
第一步·试探：双方先过1-2招试探深浅，不直接出杀招。用眼神、气息、灵力波动做铺垫。
第二步·拉锯：各出3-5招，有攻有守，有吃亏有占便宜。不能一方全程碾压。
第三步·爆发：双方同时出底牌/大招，场面最激烈。这里是高潮。
第四步·收尾：一招定胜负。收尾要干脆，留余韵（受伤、喘息、说一句话）。

=== 境界差的具体体现（不是嘴上说"他很强"，要写出来）===
- 高一个小境界：速度快半拍、力量大三分、防御厚一层（能感受到压力，但能打）
- 高一个大境界：灵压如山、站着不动就让人喘不过气、一招之内见生死
- 越级反杀：必须靠"奇兵"（特殊功法、法宝、地形、对手轻敌、付出代价），不能凭空赢

=== 五感战斗法（每个战斗场景至少用3种）===
视觉：刀光的颜色、血的飞溅轨迹、灵力碰撞的火花、瞳孔骤缩
听觉：骨裂声、剑气破空的锐鸣、闷哼、牙齿咬碎的咯吱声、风声骤停
嗅觉：血腥味、焦糊味、铁锈味、汗水的咸味
触觉：刀刃贴皮肤的寒意、拳头砸在胸口的闷震、虎口发麻、膝盖发软
本体觉：心跳擂鼓、呼吸卡在喉咙里、灵力在经脉里灼烧、后背冷汗

=== 招式描写三要素 ===
1. 起手式：动作的"预备"——握刀的手紧了紧、脚下步法一变、灵力在指尖凝聚
2. 过程中：动态的"画面"——不是"他劈了一刀"，是"刀身拖着火光斜斩而下，空气被切开发出嘶嘶锐鸣"
3. 落点处：结果的"质感"——不是"打中了"，是"刀锋切入左肩半寸，血珠顺着刀刃滚落，在地上砸开几朵小红花"

=== 代价感（赢了也要掉层皮）===
- 灵力耗尽：手脚发软、视野发黑、站立不稳
- 皮肉伤：具体位置+具体痛感（左肩被剑气擦过，火辣辣的疼，血浸透了半边袖子）
- 内伤：一口血涌到嘴边又咽回去、丹田刺痛、经脉微微发颤
- 心理代价：手在抖——不是怕，是刚才那一刀太险了

=== 心理博弈（战斗不只是拼力气）===
- 试探："他故意露出左路破绽——是陷阱，还是真的防守薄弱？"
- 误判："他以为这一剑刺的是心口，没想到对方中途变招，直奔咽喉"
- 算计："他退到崖边——不是无路可退，是要借地势反弹"
- 轻敌付出代价："周厉本来没把他放在眼里，直到那道白光钻进经脉，他才知道错了"

=== 兵器/功法的"性格"===
- 刀：霸道、直来直往、一刀两断
- 剑：飘逸、点到即止、变化多端
- 拳：厚重、贴身、骨节作响
- 法术：远程、华丽、吟唱/掐诀
- 雷系：爆裂、麻痹、速度快
- 火系：灼热、蔓延、灼烧感
- 冰系：缓慢、冻结、脆响

=== 禁忌（绝对不能写）===
❌ "他很强"——直接说强弱，不用形容词，用对比和结果体现
❌ "战斗非常激烈"——废话，直接写战斗画面
❌ 一招秒全场（除非实力差3个大境界以上，且是配角）
❌ 主角毫发无损赢了（至少受点轻伤或耗点灵力）
❌ 没有环境描写的纯打斗（战斗要跟场景结合：碎石飞溅、树木折断、地面开裂）
❌ 连续5句以上纯动作（穿插心理、感官、环境变化）

=== 收尾方式（选1种，不要每次都一样）===
A. 压倒式：最后一招轰飞，胜负已定
B. 险胜式：双方都倒了，主角先爬起来
C. 智取式：不是力气赢的，是脑子赢的
D. 留手式：主角赢了但没下死手，放对方走
E. 惨胜式：赢了，但代价很大，站都站不稳"""


