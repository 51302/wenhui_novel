def get_chapter_template_guide(template_id: str) -> str:
    """根据章节模板ID返回对应写作模板；未知ID返回空字符串"""
    if not template_id:
        return ""
    for t in CHAPTER_TEMPLATES:
        if t["id"] == template_id:
            return t["guide"]
    return ""


def get_chapter_template_list() -> list:
    """返回章节模板下拉框选项列表 [{id, name, category}]"""
    return [{"id": t["id"], "name": t["name"], "category": t["category"]} for t in CHAPTER_TEMPLATES]


