MEME_STYLE_GUIDE = """【网感风格指南 —— 适度玩梗，让文字更有那味儿】

=== 使用原则 ===
- 适度原则：一章最多 2-3 个梗，不能句句都是，不然尬
- 适配原则：现代/都市/系统/穿越题材可以多用，古风/修仙/玄幻少用（用了也要自然）
- 吐槽担当：一般由主角内心OS承担，不要让配角说不符合身份的梗
- 点到为止：梗只说一半，留一半让读者自己品，说透了就没意思了

=== 常见网梗用法速查 ===

【吐槽类】
- "沉默是今晚的康桥" → 场面尴尬时用
- "整个人都不好了" → 遭遇离谱事情时
- "这合理吗？这不合理" → 内心吐槽
- "就挺突然的" → 事情发展出乎意料
- "我谢谢你啊" → 反话，无语到极点
- "不是哥们？" → 表示震惊和不解
- "有没有一种可能" → 委婉地说对方脑子不好使

【摆烂/躺平类】
- "摆烂一时爽，一直摆烂一直爽"
- "毁灭吧，赶紧的"
- "这条命都是工资给的" / "这条命都是系统给的"
- "摸鱼是工作的一部分，不爽不要玩"

【装逼/反套路类】
- "基操，勿6，皆坐，静观" → 装逼之后
- "我不是针对谁，我是说在座的各位都是垃圾" → 慎用，太冲
- "道理我都懂，可为什么这么大？" → 双关梗
- "他急了他急了" → 对方恼羞成怒时
- "就这？就这水平？" → 轻蔑

【系统/穿越专属】
- "系统：你礼貌吗？"
- "叮——你的外挂已到账"
- "我这该死的，无处安放的魅力"
- "别人穿越我也穿越，怎么差距就这么大呢？"

【情绪表达类】
- "蚌埠住了" → 绷不住了
- "破防了" → 被戳中
- "麻了" → 麻木了
- "人麻了" / "人傻了"
- "我直接好家伙"
- "给我整不会了"

【描写替代法（用网络语气代替传统描写）】
- ❌ "他心中十分震惊" → ✅ "他人傻了" / "他直接懵了"
- ❌ "她非常生气" → ✅ "她拳头硬了" / "她血压上来了"
- ❌ "场面十分尴尬" → ✅ "空气突然安静" / "脚趾抠出三室一厅"
- ❌ "他觉得很无语" → ✅ "他一时竟不知道说什么好"

=== 注意事项 ===
- 古风/玄幻文里的梗要"降维"，不能出现手机、WiFi、互联网等现代词
- 主角穿越的可以多用，土著角色少用（除非设定就是性格跳脱）
- 严肃场景（生死、离别、悲伤）不要玩梗，破坏气氛
- 战斗高潮少玩梗，燃就完事儿了
- 日常、吐槽、过渡章节可以适当放松
- 同一个梗不要连续用，换着来"""


